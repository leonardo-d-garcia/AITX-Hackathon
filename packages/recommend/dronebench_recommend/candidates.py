"""Deterministic candidate generation (architecture section 7, step 2).

"Generate bounded candidates from failing checks and typed dependency paths." Everything here is
arithmetic and graph traversal; no model is consulted. Section 4 is explicit that this path must
produce useful proposals with no API access, so the provider adapter is an addition to this, never
a replacement for it.

Each generator answers one failing or unknown check and states the evidence it used. A generator
that cannot establish its preconditions produces nothing rather than a guess - notably, the removal
family from the tentative specification is absent entirely, because section 3 rules that missing
redundancy, manufacturing, or load-path knowledge prevents removal recommendations.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

from dronebench_contracts import (
    CatalogSnapshot,
    Claim,
    DeclaredInterface,
    Evaluation,
    EvidenceRequest,
    GeometryFeatures,
    MAX_CANDIDATES,
    Mission,
    PartOccurrence,
    PartsDocument,
    ReplaceCatalogComponent,
    ResizeSpar,
    SetWingTipExtension,
    TranslateComponent,
)
from dronebench_graph import evidence_path_to_constraint
from dronebench_contracts.graph import ExplanationPath


@dataclass(frozen=True)
class Candidate:
    """A proposal before it has been previewed."""

    key: str
    title: str
    issue: str
    operation: object
    rationale: str
    prerequisites: tuple[str, ...]
    evidence_ids: tuple[str, ...]
    answers_check_id: str | None
    evidence_path: ExplanationPath | None = None


def generate(
    *,
    parts: PartsDocument,
    features: GeometryFeatures,
    mission: Mission,
    evaluation: Evaluation,
    catalog: CatalogSnapshot,
    graph=None,
) -> tuple[list[Candidate], list[EvidenceRequest]]:
    """Return ``(candidates, evidence_requests)`` within the section 7 budget.

    Evidence requests come first in priority: an edit ranked on unknown inputs is theatre, so when
    a required check is unknown the missing fact is surfaced before any proposal that claims a gain.
    """
    requests = _evidence_requests(parts=parts, evaluation=evaluation)

    candidates: list[Candidate] = []
    candidates += _cg_candidates(parts=parts, mission=mission, evaluation=evaluation, graph=graph)
    candidates += _spar_candidates(
        parts=parts, features=features, mission=mission, evaluation=evaluation, catalog=catalog,
        graph=graph,
    )
    candidates += _energy_candidates(
        parts=parts, mission=mission, evaluation=evaluation, catalog=catalog, graph=graph
    )
    candidates += _mass_candidates(
        parts=parts, mission=mission, evaluation=evaluation, catalog=catalog, graph=graph
    )
    candidates += _span_candidates(
        parts=parts, features=features, mission=mission, evaluation=evaluation, graph=graph
    )

    # Deduplicate by the part and operation they touch; keep the earliest, which is the one
    # generated by the more urgent check.
    seen: set[tuple[str, str]] = set()
    unique: list[Candidate] = []
    for candidate in candidates:
        signature = (candidate.operation.operation, candidate.operation.target_part_id)
        if signature in seen:
            continue
        seen.add(signature)
        unique.append(candidate)

    return unique[:MAX_CANDIDATES], requests


# ---------------------------------------------------------------------------------------------
# Missing evidence
# ---------------------------------------------------------------------------------------------


def _evidence_requests(
    *, parts: PartsDocument, evaluation: Evaluation
) -> list[EvidenceRequest]:
    """One request per occurrence whose unknown mass is blocking a required check."""
    blocked = [c.check_id for c in evaluation.required_unknown()]
    if not blocked:
        return []

    requests: list[EvidenceRequest] = []
    for occurrence in parts.occurrences:
        if occurrence.mass_kg.is_known:
            continue
        requests.append(
            EvidenceRequest(
                request_id=f"req_{occurrence.part_id.replace('prt_', '')}-mass",
                base_revision_id=parts.revision_id,
                title=f"Supply a measured mass for {occurrence.name}",
                quantity=f"{occurrence.part_id}.mass_kg",
                unit="kg",
                target_part_id=occurrence.part_id,
                why_it_matters=(
                    f"{occurrence.name} has no mass evidence, so all-up mass and centre of gravity "
                    "cannot be computed, and every weight-dependent result stays unknown. A filled "
                    "bounding envelope is not a substitute: geometry does not determine mass."
                ),
                blocked_check_ids=blocked,
                suggested_source_kinds=["bom", "manual"],
            )
        )
    return requests


# ---------------------------------------------------------------------------------------------
# Centre of gravity
# ---------------------------------------------------------------------------------------------


def _cg_candidates(*, parts, mission: Mission, evaluation: Evaluation, graph) -> list[Candidate]:
    """Move a movable mass along its corridor to bring the CG inside the envelope.

    Only mount positions that are actually available are proposed, and the move must land the CG
    inside the envelope by calculation before it is offered. Section 7 step 5 still previews it for
    real; this is a screen, not a promise.
    """
    check = _check(evaluation, "cg_envelope")
    if check is None or check.status not in ("fail",):
        return []

    total_mass, moment_x = _mass_and_moment(parts)
    if total_mass is None or moment_x is None:
        return []

    lo, hi = mission.cg_envelope_station_m
    target_station = (lo + hi) / 2
    out: list[Candidate] = []

    for occurrence in parts.occurrences:
        if "translate_component" not in occurrence.edit_capabilities:
            continue
        if occurrence.locked or occurrence.part_id in mission.locked_part_ids:
            continue
        corridor = occurrence.travel_corridor
        mass = occurrence.mass_kg.number()
        if corridor is None or mass is None or corridor.axis != "x":
            continue

        current_x = occurrence.transform.translation[0]
        # Moving this mass by d changes x_CG by mass*d/total. Solve for the d that centres the CG.
        wanted_delta = (-target_station - (moment_x / total_mass)) * total_mass / mass

        options = corridor.mount_positions_m or [corridor.min_m, corridor.max_m]
        feasible = []
        for position in options:
            delta = position - current_x
            if delta == 0.0 or not corridor.contains(position):
                continue
            station = -((moment_x + mass * delta) / total_mass)
            if lo <= station <= hi:
                feasible.append((abs(delta), delta, position, station))
        if not feasible:
            continue

        # Smallest move that works: section 10 wants the minimum intelligible change, and a short
        # travel keeps the harness allowance comfortable.
        _, delta, position, station = min(feasible)

        path = (
            evidence_path_to_constraint(graph, occurrence.part_id, "cg_envelope")
            if graph is not None
            else None
        )
        out.append(
            Candidate(
                key=f"{occurrence.part_id}-cg",
                title=f"Move {occurrence.name} forward {abs(delta) * 1000:.0f} mm",
                issue=(
                    f"Centre of gravity is at station {-(moment_x / total_mass):.3f} m, outside the "
                    f"{lo:.3f}-{hi:.3f} m envelope."
                ),
                operation=TranslateComponent(
                    target_part_id=occurrence.part_id,
                    axis="x",
                    delta_m=round(delta, 6),
                ),
                rationale=(
                    f"Relocating {mass:.3f} kg by {delta * 1000:+.0f} mm along the declared "
                    f"corridor moves the centre of gravity to station {station:.3f} m, inside the "
                    f"envelope. The mount position {position:+.3f} m is one of the corridor's "
                    "declared positions and the harness allowance covers the travel. Geometry "
                    "shapes are unchanged - this is a placement change, so fixed-geometry "
                    "aerodynamic coefficients may be reused."
                ),
                prerequisites=(
                    "travel corridor declared",
                    "harness allowance known",
                    "mount positions known",
                    f"{occurrence.part_id} mass established from BOM evidence",
                ),
                evidence_ids=tuple(occurrence.mass_kg.evidence_ids),
                answers_check_id="cg_envelope",
                evidence_path=path,
            )
        )
    return out


