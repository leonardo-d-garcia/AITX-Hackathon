def _energy_candidates(
    *, parts, mission: Mission, evaluation: Evaluation, catalog: CatalogSnapshot, graph
) -> list[Candidate]:
    """Swap to a higher-capacity pack that actually fits the bay and the electrical model."""
    check = _check(evaluation, "energy_reserve")
    if check is None or check.status != "fail":
        return []
    return _battery_swap(
        parts=parts,
        mission=mission,
        catalog=catalog,
        graph=graph,
        prefer="capacity",
        issue=check.reason,
        answers="energy_reserve",
    )


def _mass_candidates(
    *, parts, mission: Mission, evaluation: Evaluation, catalog: CatalogSnapshot, graph
) -> list[Candidate]:
    """Swap to a lighter pack when the mass budget is the binding constraint."""
    check = _check(evaluation, "mass_budget")
    if check is None or check.status != "fail":
        return []
    return _battery_swap(
        parts=parts,
        mission=mission,
        catalog=catalog,
        graph=graph,
        prefer="mass",
        issue=check.reason,
        answers="mass_budget",
    )


def _battery_swap(
    *, parts, mission: Mission, catalog: CatalogSnapshot, graph, prefer: str, issue: str, answers: str
) -> list[Candidate]:
    batteries = [
        o
        for o in parts.occurrences
        if o.role == "battery" and "replace_catalog_component" in o.edit_capabilities
    ]
    if not batteries:
        return []
    battery = batteries[0]
    current_mass = battery.mass_kg.number()
    bay = _bay_interface(parts, battery)

    fitting = []
    for item in catalog.of_category("battery"):
        envelope = item.interface_of("mass_envelope")
        if envelope is None:
            continue
        fits, _ = bay.fits(envelope)
        if not fits:
            continue
        electrical = item.interface_of("electrical_dc")
        if electrical is None or electrical.voltage_v is None:
            continue
        # The existing ESC and motor were selected for the current pack voltage. A different
        # voltage class is a different electrical model, which this operation does not cover.
        current_electrical = _current_pack_voltage(catalog, parts, battery)
        if current_electrical is not None and not _voltage_compatible(
            electrical.voltage_v, current_electrical
        ):
            continue
        capacity = item.claims.get("capacity_wh")
        mass = item.mass_kg.number()
        if capacity is None or mass is None:
            continue
        capacity_v = capacity.number()
        if capacity_v is None:
            continue
        fitting.append((capacity_v, mass, item))

    if not fitting:
        return []

    if prefer == "capacity":
        capacity_v, mass, item = max(fitting, key=lambda row: row[0])
    else:
        capacity_v, mass, item = min(fitting, key=lambda row: row[1])

    if current_mass is not None and abs(mass - current_mass) < 1e-9:
        return []

    return [
        Candidate(
            key=f"{battery.part_id}-swap-{item.catalog_item_id}",
            title=f"Replace the pack with {item.display_name}",
            issue=issue,
            operation=ReplaceCatalogComponent(
                target_part_id=battery.part_id, catalog_item_id=item.catalog_item_id
            ),
            rationale=(
                f"{item.display_name} carries {capacity_v:.1f} Wh at {mass:.3f} kg and fits the "
                "declared bay envelope and the existing pack voltage class. The BOM entry and the "
                "envelope are replaced atomically; unresolved fit or current checks block the "
                "commit rather than warning. This is a synthetic catalog entry with no implied "
                "real supplier offer."
            ),
            prerequisites=(
                "bay envelope declared",
                "pack voltage class matches the installed ESC",
                "mass and capacity present in the catalog snapshot",
            ),
            evidence_ids=tuple(item.evidence_ids),
            answers_check_id=answers,
            evidence_path=(
                evidence_path_to_constraint(graph, battery.part_id, answers)
                if graph is not None
                else None
            ),
        )
    ]


def _span_candidates(
    *, parts, features: GeometryFeatures, mission: Mission, evaluation: Evaluation, graph
) -> list[Candidate]:
    """A bounded tip extension, only when the endurance objective is the thing being pushed.

    This is the stretch operation of section 6 and the only one that invalidates the aerodynamic
    geometry, so it is offered last and only when the airframe has mass headroom for it.
    """
    check = _check(evaluation, "energy_reserve")
    if check is None or check.status != "fail":
        return []

    tips = [o for o in parts.occurrences if "set_wing_tip_extension" in o.edit_capabilities]
    if len(tips) < 2:
        return []
    left = next((o for o in tips if o.mirror_of is None), None)
    right = next((o for o in tips if o.mirror_of == (left.part_id if left else None)), None)
    if left is None or right is None:
        return []

    span = features.wing_span_m.number()
    if span is None:
        return []
    extension = 0.05  # 50 mm per side: bounded, and within the joint model of the fixture

    return [
        Candidate(
            key=f"{left.part_id}-tip",
            title=f"Extend each wing tip by {extension * 1000:.0f} mm",
            issue=check.reason,
            operation=SetWingTipExtension(
                target_part_id=left.part_id, extension_m=extension, paired_part_id=right.part_id
            ),
            rationale=(
                f"Span rises from {span:.2f} m to {span + 2 * extension:.2f} m, raising aspect "
                "ratio and lowering induced drag at the locked cruise condition. This changes the "
                "outer mold line, so the aerodynamic geometry is invalidated and both baseline and "
                "candidate must be re-solved at the same fidelity before any gain is shown."
            ),
            prerequisites=(
                "parameterised symmetric tip",
                "bounded span and a joint model",
                "both occurrences regenerated in one transaction",
            ),
            evidence_ids=tuple(features.wing_span_m.evidence_ids),
            answers_check_id="energy_reserve",
            evidence_path=(
                evidence_path_to_constraint(graph, left.part_id, "energy_reserve")
                if graph is not None
                else None
            ),
        )
    ]


# ---------------------------------------------------------------------------------------------
# Shared arithmetic
# ---------------------------------------------------------------------------------------------


def _check(evaluation: Evaluation, check_id: str):
    try:
        return evaluation.check(check_id)
    except KeyError:
        return None


def _mass_and_moment(parts: PartsDocument) -> tuple[float | None, float | None]:
    """``(total mass, sum of m*x)``. Returns ``(None, None)`` if any mass is unknown.

    Section 8: massless or missing-mass geometry does not quietly disappear.
    """
    total = 0.0
    moment = 0.0
    for occurrence in parts.occurrences:
        mass = occurrence.mass_kg.number()
        if mass is None:
            return None, None
        com = occurrence.world_com_m()
        if com is None:
            return None, None
        total += mass
        moment += mass * com[0]
    return (total, moment) if total > 0 else (None, None)


def _tube_mass(outer: float, inner: float, length: float, density: float) -> float:
    return math.pi * (outer**2 - inner**2) / 4.0 * length * density


def _second_moment(outer: float, inner: float) -> float:
    """``I = pi (Do^4 - Di^4) / 64`` for a tube."""
    return math.pi * (outer**4 - inner**4) / 64.0


def _bay_interface(parts: PartsDocument, battery: PartOccurrence) -> DeclaredInterface:
    """The envelope a replacement pack must fit inside, taken from the installed part's bounds."""
    bounds = battery.bounds_local_m
    if bounds is None:
        return DeclaredInterface(
            interface_id="if_bay_unknown", kind="mass_envelope", dimensions_m={}
        )
    length, width, height = bounds.size_m
    # A small allowance for the bay around the installed pack, from the declared harness allowance.
    slack = 0.005
    return DeclaredInterface(
        interface_id="if_bay_battery",
        kind="mass_envelope",
        dimensions_m={
            "length_max": length + slack,
            "width_max": width + slack,
            "height_max": height + slack,
        },
    )


def _current_pack_voltage(
    catalog: CatalogSnapshot, parts: PartsDocument, battery: PartOccurrence
) -> tuple[float, float] | None:
    """Voltage window of the pack currently installed, matched by mass and envelope."""
    installed_mass = battery.mass_kg.number()
    if installed_mass is None:
        return None
    for item in catalog.of_category("battery"):
        item_mass = item.mass_kg.number()
        if item_mass is None or abs(item_mass - installed_mass) > 1e-6:
            continue
        electrical = item.interface_of("electrical_dc")
        if electrical and electrical.voltage_v:
            return electrical.voltage_v
    return None


def _voltage_compatible(
    candidate: tuple[float, float], installed: tuple[float, float]
) -> bool:
    """Same voltage class: the windows must overlap substantially, not merely touch."""
    lo = max(candidate[0], installed[0])
    hi = min(candidate[1], installed[1])
    if hi <= lo:
        return False
    installed_width = installed[1] - installed[0]
    return (hi - lo) >= 0.5 * installed_width
