# Spar
# ---------------------------------------------------------------------------------------------


def _spar_candidates(
    *, parts, features, mission: Mission, evaluation: Evaluation, catalog: CatalogSnapshot, graph
) -> list[Candidate]:
    """Offer the next compatible tube up.

    Generated when the stress check fails, and also when it passes with headroom in the mass
    budget - section 14 wants a spar proposal whose tradeoff (more margin, more mass) is visible
    enough to decline. Either way the mass cost is stated in the rationale, never hidden.
    """
    check = _check(evaluation, "spar_stress")
    if check is None or check.status == "not_applicable":
        return []

    spars = [o for o in parts.occurrences if "resize_spar" in o.edit_capabilities]
    if not spars:
        return []
    spar = spars[0]

    definition = parts.definition(spar.definition_id)
    current_outer = definition.parameters.get("outer_diameter_m")
    current_inner = definition.parameters.get("inner_diameter_m")
    length = definition.parameters.get("length_m")
    if current_outer is None or current_inner is None or length is None:
        return []

    density = definition.claims.number("density_kgm3")
    allowable = definition.claims.number("allowable_stress_pa")
    if density is None or allowable is None:
        # Section 6: the material assumption must be declared before a resize is proposable.
        return []

    current_mass = _tube_mass(current_outer, current_inner, length, density)
    total_mass, _ = _mass_and_moment(parts)

    upgrades = []
    for item in catalog.of_category("spar"):
        outer = item.claims.get("outer_diameter_m")
        inner = item.claims.get("inner_diameter_m")
        if outer is None or inner is None:
            continue
        outer_v, inner_v = outer.number(), inner.number()
        if outer_v is None or inner_v is None or outer_v <= current_outer:
            continue
        upgrades.append((outer_v, inner_v, item))
    if not upgrades:
        return []

    outer_v, inner_v, item = min(upgrades)
    new_mass = _tube_mass(outer_v, inner_v, length, density)
    delta_mass = new_mass - current_mass

    if total_mass is not None:
        headroom = mission.max_takeoff_mass_kg - total_mass
        if delta_mass > headroom:
            # Proposing an edit that would immediately break the mass budget is not a proposal.
            return []

    current_i = _second_moment(current_outer, current_inner)
    new_i = _second_moment(outer_v, inner_v)
    margin_ratio = (new_i / current_i) * (current_outer / outer_v)

    failing = check.status == "fail"
    path = (
        evidence_path_to_constraint(graph, spar.part_id, "spar_stress")
        if graph is not None
        else None
    )
    return [
        Candidate(
            key=f"{spar.part_id}-resize",
            title=(
                f"Increase the spar to {outer_v * 1000:.0f} x {inner_v * 1000:.0f} mm"
            ),
            issue=(
                check.reason
                if failing
                else (
                    "Root bending stress is within allowable, but the structural margin can be "
                    "raised at a stated mass cost."
                )
            ),
            operation=ResizeSpar(
                target_part_id=spar.part_id,
                outer_diameter_m=outer_v,
                inner_diameter_m=inner_v,
                regenerate_mount_part_ids=[
                    o.part_id
                    for o in parts.occurrences
                    if o.role == "mount" and spar.part_id in o.allowed_contact_part_ids
                ],
            ),
            rationale=(
                f"The section modulus rises by a factor of {margin_ratio:.2f}, lowering root "
                f"bending stress by the same factor. It costs {delta_mass * 1000:+.0f} g, which "
                "shifts the mass budget and the centre of gravity, and the two compatible mounts "
                "are regenerated inside the same transaction. Bending stress alone omits buckling, "
                "joints, adhesive, and local damage; this proposal does not claim those are "
                "addressed."
            ),
            prerequisites=(
                "reconstructed tubular spar",
                "material density and allowable stress declared",
                "compatible mount bore regenerated in the same transaction",
            ),
            evidence_ids=tuple(item.evidence_ids) + tuple(
                definition.claims.get("allowable_stress_pa").evidence_ids  # type: ignore[union-attr]
            ),
            answers_check_id="spar_stress" if failing else None,
            evidence_path=path,
        )
    ]


